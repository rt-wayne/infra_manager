-- ===== 1. 改寫前計數（唯讀）
-- TO_FIX＝會被改寫的筆數；已是中文名、'系統排程'、對不上的筆數見第 3 段（改寫前跑第 3 段也可以，先看全貌）。
-- 舊版寫法對照表（每位英文名、中文名都有值的使用者一列）：
WITH OLD_NAME AS (
