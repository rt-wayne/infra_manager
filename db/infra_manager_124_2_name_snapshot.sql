SELECT 'IM_ACCT_HIST.ACT_BY_NAME' AS COL_NAME, COUNT(*) AS TO_FIX FROM IM_ACCT_HIST T WHERE T.ACT_BY_NAME IN (SELECT OLD_TEXT FROM OLD_NAME)
