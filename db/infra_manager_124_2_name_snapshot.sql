SELECT 'IM_ACCT_HIST.ACT_AS_NAME', COUNT(*) FROM IM_ACCT_HIST T WHERE T.ACT_AS_NAME IN (SELECT OLD_TEXT FROM OLD_NAME)
UNION ALL
